"""Isolated advisory teaching intelligence; intentionally not wired to HTTP.

Registry and turn context must be assembled by trusted server code. Neither
lexical observations nor strategy suggestions accept evidence or award progress.
No student identity, transcript or conversation history enters the model prompt.
"""
from __future__ import annotations

import asyncio
import json
import os
import re
import unicodedata
from enum import Enum
from typing import Literal

import httpx
from pydantic import BaseModel, ConfigDict, Field, model_validator

from .class1_language import resolve_support_language


class Strategy(str, Enum):
    DIAGNOSE = "DIAGNOSE"
    EXPLAIN = "EXPLAIN"
    MODEL = "MODEL"
    ASK = "ASK"
    GUIDE = "GUIDE"
    LISTEN = "LISTEN"
    CORRECT = "CORRECT"
    RETEACH = "RETEACH"
    INDEPENDENT_CHECK = "INDEPENDENT_CHECK"
    REVISION = "REVISION"
    RECALL = "RECALL"


class Observation(str, Enum):
    MATCH = "MATCH"
    PARTIAL = "PARTIAL"
    MISMATCH = "MISMATCH"
    AMBIGUOUS = "AMBIGUOUS"
    UNAVAILABLE = "UNAVAILABLE"
    OFF_TOPIC = "OFF_TOPIC"


class FrozenModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)


def normalize(text: str) -> str:
    return " ".join(re.findall(r"[^\W_]+", unicodedata.normalize("NFKC", text).casefold()))


# Defense in depth for server-authored cards, not a general child-safety classifier.
UNSAFE = re.compile(
    r"https?://|www\.|[<>{}\[\]]|\b(?:password|phone|address|email|secret|"
    r"unlock|mastered|xp|iq|score|perfect|stupid|idiot|kill|sex|"
    r"your name|your school name|ignore instructions|system prompt)\b", re.I
)


class Card(FrozenModel):
    strategy: Strategy
    language: Literal["en", "hi", "mr"]
    # Alternatives are curriculum-owner-authored, never generated by the LLM.
    variants: tuple[str, ...] = Field(min_length=1, max_length=4)
    question: str = Field(min_length=1, max_length=200)
    supplies_answer: bool = False
    model_sentence: str | None = Field(default=None, max_length=200)

    @model_validator(mode="after")
    def safe_content(self):
        if any(not text.strip() for text in (*self.variants, self.question)):
            raise ValueError("Missing authored teaching wording")
        for text in (*self.variants, self.question, self.model_sentence or ""):
            if len(text) > 240 or UNSAFE.search(text) or any(
                unicodedata.category(char).startswith("C") for char in text
            ):
                raise ValueError("Unsafe or oversized authored teaching card")
        if self.strategy in (Strategy.INDEPENDENT_CHECK, Strategy.RECALL):
            if self.supplies_answer or self.model_sentence:
                raise ValueError("Independent/recall cards cannot supply an answer")
        if self.model_sentence and not self.supplies_answer:
            raise ValueError("An example must be marked as answer-bearing support")
        return self


class Objective(FrozenModel):
    """Internal curriculum adapter, NOT a replacement Z.ai dataset schema.

    The review reference records provenance, not proof of authorization. Only a
    trusted caller may populate this registry. Synthetic objectives are test-only.
    """
    objective_id: str = Field(min_length=1, max_length=80)
    activity_id: str = Field(min_length=1, max_length=80)
    lesson_id: str = Field(min_length=1, max_length=80)
    version: str = Field(min_length=1, max_length=80)
    grade: int = Field(ge=0, le=10)
    review_reference: str = Field(min_length=1, max_length=200)
    synthetic: bool = False
    allowed_vocabulary: tuple[str, ...] = Field(min_length=1, max_length=100)
    # Exact lexical matches are advisory, never semantic or pronunciation scores.
    expected_answers: tuple[str, ...] = Field(min_length=1, max_length=20)
    partial_terms: tuple[str, ...] = Field(default=(), max_length=30)
    recall_required: bool = False
    cards: tuple[Card, ...] = Field(min_length=1, max_length=100)

    @model_validator(mode="after")
    def reviewed_cards(self):
        if not self.review_reference.strip() or any(not normalize(x) for x in self.expected_answers):
            raise ValueError("Missing reviewed rubric")
        if any(len(text) > 200 for text in (*self.expected_answers, *self.partial_terms, *self.allowed_vocabulary)):
            raise ValueError("Oversized rubric content")
        keys = [(card.strategy, card.language) for card in self.cards]
        if len(set(keys)) != len(keys):
            raise ValueError("Duplicate strategy/language cards")
        languages = {card.language for card in self.cards}
        for language in languages:
            if any((strategy, language) not in keys for strategy in Strategy):
                raise ValueError("Every offered language needs all teaching strategies")
        if any(not word.strip() or UNSAFE.search(word) for word in self.allowed_vocabulary):
            raise ValueError("Invalid approved vocabulary")
        vocabulary = set(normalize(" ".join(self.allowed_vocabulary)).split())
        # All English learning answers must use the reviewed learning vocabulary.
        if any(not set(normalize(answer).split()) <= vocabulary for answer in self.expected_answers):
            raise ValueError("Answer outside approved vocabulary")
        # Age limits apply to each authored variant; older grades keep their own content.
        limit = 22 if self.grade <= 1 else 40
        for card in self.cards:
            if any(len(text.split()) > limit for text in (*card.variants, card.question)):
                raise ValueError("Teaching wording exceeds age limit")
            # An independent card may not quietly reveal the expected answer.
            if card.strategy in (Strategy.INDEPENDENT_CHECK, Strategy.RECALL):
                wording = " " + normalize(" ".join((*card.variants, card.question))) + " "
                if any(" " + normalize(answer) + " " in wording for answer in self.expected_answers):
                    raise ValueError("Independent check reveals the rubric answer")
        return self

    @property
    def key(self) -> tuple[str, str, str, str]:
        return self.lesson_id, self.activity_id, self.objective_id, self.version


class Turn(FrozenModel):
    transcript: str = Field(default="", max_length=1000)
    input_status: Literal["TEXT", "SPEECH", "SILENCE", "STT_FAILED", "NO_MIC"] = "TEXT"
    intent: Literal["START", "ANSWER", "EXPLAIN", "MODEL", "HINT", "LISTEN", "REVISE", "RECALL"] = "ANSWER"
    language: Literal["en", "hi", "mr"] = "en"
    prior_strategy: Strategy | None = None
    mistakes: int = Field(default=0, ge=0, le=20)
    hint_level: int = Field(default=0, ge=0, le=3)
    supported: bool = False
    # Trusted context from Node, scoped to this objective/version, not from a pupil.
    supplied_examples: tuple[str, ...] = Field(default=(), max_length=12)
    recall_due: bool = False


class Decision(FrozenModel):
    strategy: Strategy
    observation: Observation
    answer_support: Literal["SUPPORTED", "UNVERIFIED_INDEPENDENT", "UNKNOWN"]
    language: Literal["en", "hi", "mr"]


INJECTION = re.compile(
    r"\b(?:ignore|override|system prompt|developer message|unlock|award|password|"
    r"pretend|instructions|forget the lesson)\b|निर्देश.*अनदेखा|सूचना.*दुर्लक्ष", re.I
)
HELP = re.compile(
    r"\b(?:help|explain|meaning|don.t know|do not know|hindi|marathi)\b|"
    r"समझ|समज|मतलब|म्हणजे|मदद", re.I
)


def observe(objective: Objective, turn: Turn) -> Observation:
    """Conservative lexical observation, explicitly not a correctness verdict."""
    if turn.input_status in ("SILENCE", "STT_FAILED", "NO_MIC") or not turn.transcript.strip():
        return Observation.UNAVAILABLE
    if INJECTION.search(unicodedata.normalize("NFKC", turn.transcript)):
        return Observation.OFF_TOPIC
    text = normalize(turn.transcript)
    if "?" in turn.transcript or HELP.search(turn.transcript):
        return Observation.AMBIGUOUS
    if text in {normalize(answer) for answer in objective.expected_answers}:
        return Observation.MATCH
    tokens = set(text.split())
    if tokens & set(normalize(" ".join(objective.partial_terms)).split()):
        return Observation.PARTIAL
    if not tokens & set(normalize(" ".join(objective.allowed_vocabulary)).split()):
        return Observation.OFF_TOPIC
    return Observation.MISMATCH


def decide(objective: Objective, turn: Turn) -> Decision:
    observation = observe(objective, turn)
    language = resolve_support_language(turn.language, turn.transcript) or turn.language
    contaminated = (
        turn.supported or turn.hint_level > 0 or
        turn.prior_strategy in (Strategy.EXPLAIN, Strategy.MODEL, Strategy.GUIDE, Strategy.CORRECT, Strategy.RETEACH, Strategy.REVISION) or
        normalize(turn.transcript) in {normalize(x) for x in turn.supplied_examples}
    )
    support = ("SUPPORTED" if contaminated else "UNVERIFIED_INDEPENDENT") if observation == Observation.MATCH else "UNKNOWN"
    if observation == Observation.OFF_TOPIC:
        strategy = Strategy.ASK
    elif turn.intent == "START" and turn.input_status in ("TEXT", "SPEECH"):
        strategy = Strategy.DIAGNOSE
    elif observation == Observation.UNAVAILABLE:
        strategy = Strategy.LISTEN
    elif turn.intent == "LISTEN":
        strategy = Strategy.LISTEN
    elif turn.intent == "REVISE" or turn.mistakes >= 5:
        strategy = Strategy.REVISION
    elif turn.intent == "RECALL":
        strategy = Strategy.RECALL if objective.recall_required and turn.recall_due else Strategy.INDEPENDENT_CHECK
    elif turn.intent == "MODEL":
        strategy = Strategy.MODEL
    elif turn.intent == "EXPLAIN" or observation == Observation.AMBIGUOUS:
        strategy = Strategy.RETEACH if turn.prior_strategy == Strategy.EXPLAIN or turn.mistakes >= 2 else Strategy.EXPLAIN
    elif turn.intent == "HINT":
        strategy = Strategy.GUIDE
    elif observation == Observation.MATCH:
        # Even a matching answer requests another check, never marks mastery.
        strategy = Strategy.RECALL if objective.recall_required and turn.recall_due and not contaminated else Strategy.INDEPENDENT_CHECK
    elif turn.mistakes >= 2 or turn.prior_strategy in (Strategy.CORRECT, Strategy.GUIDE):
        strategy = Strategy.RETEACH
    elif observation == Observation.PARTIAL:
        strategy = Strategy.GUIDE
    else:
        strategy = Strategy.CORRECT
    return Decision(strategy=strategy, observation=observation, answer_support=support, language=language)


class ObjectiveUnavailable(ValueError):
    """No authorized reviewed objective/card exists; do not invent a lesson."""


class Registry:
    def __init__(self, objectives: tuple[Objective, ...], *, allow_synthetic: bool = False):
        self._objectives = {}
        for objective in objectives:
            if objective.synthetic and not allow_synthetic:
                raise ObjectiveUnavailable("Synthetic curriculum is test-only")
            if objective.key in self._objectives:
                raise ObjectiveUnavailable("Duplicate objective identity")
            self._objectives[objective.key] = objective

    def resolve(self, key: tuple[str, str, str, str], *, grade: int,
                authorized_keys: frozenset[tuple[str, str, str, str]]) -> Objective:
        # Permission must come from Node/trusted server code, never an HTTP extra field.
        objective = self._objectives.get(key)
        if key not in authorized_keys or objective is None or objective.grade != grade:
            raise ObjectiveUnavailable("Unauthorized or unknown reviewed objective")
        return objective


class Choice(FrozenModel):
    wordingIndex: int = Field(ge=0, le=3)


class QwenWordingSelector:
    """Local Qwen chooses only a reviewed wording index; no arbitrary model text.

    Two attempts at most under one wall-clock deadline, including connection
    and response parsing. One transient retry only. Never switches providers.
    """
    def __init__(self, *, timeout: float = 4.0, client: httpx.AsyncClient | None = None):
        if not 0 < timeout <= 6:
            raise ValueError("Selector deadline must be at most six seconds")
        self.timeout = timeout
        self.client = client

    async def select(self, *, grade: int, decision: Decision, card: Card) -> int | None:
        address = os.getenv("OLLAMA_URL", "http://127.0.0.1:11434").rstrip("/")
        if address not in ("http://127.0.0.1:11434", "http://localhost:11434"):
            return None
        # Intentionally no transcript, pupil identity, history, secrets or rubric answers.
        payload = {
            "model": os.getenv("OLLAMA_MODEL", "qwen3:4b-instruct"),
            "stream": False, "format": "json",
            "options": {"temperature": 0, "num_predict": 24},
            "messages": [
                {"role": "system", "content": 'Choose a reviewed teaching wording. Return only {"wordingIndex":0} with a valid candidate index. Never add text or keys.'},
                {"role": "user", "content": json.dumps({
                    "grade": grade, "strategy": decision.strategy.value,
                    "observation": decision.observation.value, "language": decision.language,
                    "candidates": card.variants,
                }, ensure_ascii=False)},
            ],
        }

        async def request(client: httpx.AsyncClient) -> int | None:
            for attempt in range(2):
                try:
                    # Stream and bound upstream bytes before decoding, even for faulty Ollama.
                    async with client.stream("POST", address + "/api/chat", json=payload) as response:
                        response.raise_for_status()
                        raw = bytearray()
                        async for chunk in response.aiter_bytes(chunk_size=1024):
                            raw.extend(chunk)
                            if len(raw) > 8192:
                                return None
                    content = json.loads(raw)["message"]["content"]
                    if not isinstance(content, str) or len(content) > 128:
                        return None
                    choice = Choice.model_validate_json(content)
                    return choice.wordingIndex if choice.wordingIndex < len(card.variants) else None
                except httpx.HTTPStatusError as exc:
                    if attempt or exc.response.status_code < 500:
                        return None
                except httpx.TransportError:
                    if attempt:
                        return None
                except (ValueError, KeyError, TypeError):
                    return None
            return None

        try:
            async with asyncio.timeout(self.timeout):
                if self.client is not None:
                    return await request(self.client)
                async with httpx.AsyncClient(timeout=self.timeout, trust_env=False) as client:
                    return await request(client)
        except (TimeoutError, httpx.HTTPError):
            return None


class Guidance(FrozenModel):
    decision: Decision
    message: str
    question: str
    model_sentence: str | None
    supplies_answer: bool
    wording_source: Literal["reviewed", "qwen-selected"]

    def legacy_response(self) -> dict:
        """Contract preview for tests/review only; never installed on a route."""
        strategies = {
            Strategy.MODEL: "MODEL_SENTENCE", Strategy.GUIDE: "GIVE_HINT",
            Strategy.CORRECT: "GENTLE_CORRECTION", Strategy.RETEACH: "MODEL_SENTENCE",
            Strategy.LISTEN: "CLARIFY", Strategy.EXPLAIN: "CLARIFY",
        }
        action = strategies.get(self.decision.strategy, "ASK_FOLLOW_UP")
        quality = "UNCLEAR" if self.decision.observation in (
            Observation.UNAVAILABLE, Observation.AMBIGUOUS, Observation.OFF_TOPIC
        ) else "ADEQUATE" if self.decision.observation == Observation.MATCH else "PARTIAL"
        return {
            "message": self.message, "reaction": "encouraging", "responseQuality": quality,
            "followUpQuestion": self.question,
            "correction": {"needed": False, "original": "", "corrected": "", "explanation": ""},
            "memoryUpdates": [], "recommendedAction": action, "teachingAction": action,
            "modelSentence": self.model_sentence, "activityComplete": False,
            "shouldRetry": self.decision.strategy in (Strategy.GUIDE, Strategy.CORRECT, Strategy.RETEACH),
            "hintLevel": 1 if self.supplies_answer else 0,
            "detectedSkills": [], "remainingSkills": [],
        }


class TeachingBrain:
    def __init__(self, registry: Registry, *, selector: QwenWordingSelector | None = None):
        self.registry, self.selector = registry, selector

    async def respond(self, key: tuple[str, str, str, str], turn: Turn, *, grade: int,
                      authorized_keys: frozenset[tuple[str, str, str, str]]) -> Guidance:
        objective = self.registry.resolve(key, grade=grade, authorized_keys=authorized_keys)
        decision = decide(objective, turn)
        card = next((c for c in objective.cards if c.strategy == decision.strategy and c.language == decision.language), None)
        if card is None:
            raise ObjectiveUnavailable("No reviewed scaffold for requested language")
        # Rotate alternate explanations deterministically even with Ollama stopped.
        index = turn.mistakes % len(card.variants)
        source = "reviewed"
        if self.selector is not None and turn.mistakes < 2 and decision.observation not in (Observation.UNAVAILABLE, Observation.OFF_TOPIC):
            selected = await self.selector.select(grade=grade, decision=decision, card=card)
            if selected is not None:
                index = selected
                source = "qwen-selected"
        return Guidance(decision=decision, message=card.variants[index], question=card.question,
                        model_sentence=card.model_sentence, supplies_answer=card.supplies_answer,
                        wording_source=source)
